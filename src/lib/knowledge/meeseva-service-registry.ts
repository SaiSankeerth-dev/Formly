// Helper to lookup service by ID, shortCode, schemeId, or alias
export function getStructuredServiceById(idOrCode: string): StructuredGovernmentService | undefined {
  if (!idOrCode) return undefined;
  const normId = idOrCode.toLowerCase().trim();
  return STRUCTURED_GOVERNMENT_SERVICES.find(
    (s) =>
      s.id.toLowerCase() === normId ||
      s.shortCode.toLowerCase() === normId ||
      (s.schemeId && s.schemeId.toLowerCase() === normId) ||
      (s.aliases && s.aliases.some((a) => a.toLowerCase() === normId))
  );
}

// Helper to filter services by category
export function getStructuredServicesByCategory(category: ServiceCategory): StructuredGovernmentService[] {
  return STRUCTURED_GOVERNMENT_SERVICES.filter((s) => s.category.toLowerCase() === category.toLowerCase());
}

